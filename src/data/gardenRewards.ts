export function getNewlyUnlocked(
  previousIds: string[],
  garden: Parameters<UnlockableItem['check']>[0],
  entries: MoodEntry[],
): UnlockableItem[] {
  return UNLOCKABLE_ITEMS.filter(
    (item) => !previousIds.includes(item.id) && item.check(garden, entries),
  )
}

