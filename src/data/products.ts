function svgLamp(style: string, glow = false): string {
  const glowFilter = glow
    ? `<defs><radialGradient id="g" cx="50%" cy="35%" r="50%"><stop offset="0%" stop-color="%23FFDCA0" stop-opacity="0.9"/><stop offset="100%" stop-color="%23F4B65B" stop-opacity="0"/></radialGradient></defs><circle cx="200" cy="140" r="90" fill="url(%23g)"/>`
    : ''
  const body =
    style === 'pendant'
      ? `<rect x="196" y="40" width="8" height="70" fill="%23C9A46C"/><ellipse cx="200" cy="150" rx="70" ry="40" fill="%23F7F1E4"/><ellipse cx="200" cy="145" rx="40" ry="20" fill="%23FFDCA0" opacity="${glow ? '0.9' : '0.2'}"/>`
      : style === 'wall'
        ? `<rect x="120" y="150" width="40" height="12" rx="4" fill="%23C8CDD4"/><path d="M160 156 C190 120 240 120 260 156" stroke="%23C9A46C" stroke-width="8" fill="none"/><circle cx="260" cy="156" r="28" fill="%23F7F1E4"/><circle cx="260" cy="156" r="14" fill="%23FFDCA0" opacity="${glow ? '0.95' : '0.25'}"/>`
        : style === 'table' || style === 'desk'
          ? `<rect x="150" y="250" width="100" height="12" rx="6" fill="%231A1A1A"/><rect x="192" y="140" width="16" height="110" fill="%23C9A46C"/><path d="M140 140 Q200 60 260 140" fill="%23F7F1E4"/><ellipse cx="200" cy="140" rx="30" ry="12" fill="%23FFDCA0" opacity="${glow ? '0.9' : '0.2'}"/>`
          : `<ellipse cx="200" cy="300" rx="55" ry="10" fill="%231A1A1A"/><path d="M160 300 C120 220 150 120 200 90 C250 120 280 220 240 300" stroke="%23C9A46C" stroke-width="10" fill="none"/><circle cx="200" cy="90" r="34" fill="%23F7F1E4"/><circle cx="200" cy="90" r="16" fill="%23FFDCA0" opacity="${glow ? '0.95' : '0.2'}"/>`

  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 400 360" width="800" height="720"><rect width="400" height="360" fill="%23141414"/>${glowFilter}${body}</svg>`
  return `data:image/svg+xml,${svg}`
}

